SELECT * FROM CUSTOMER;
SELECT * FROM ORDERS;

-- Sub Queries with where 

SELECT * 
FROM ORDERS
WHERE AMOUNT > (
    SELECT AVG(AMOUNT)
    FROM ORDERS
);


-- sub queries with select 

SELECT NAME ,
 (
		SELECT COUNT(*)
		FROM ORDERS O
		WHERE O.CUS_ID = C.CUS_ID
  ) AS ORDER_COUNT
FROM CUSTOMER C;




-- SUB QUERIES WITH FORM 
SELECT 
	SUMMARY.CUS_ID,
    SUMMARY.avg_amount
FROM
	(
		SELECT 
			CUS_ID,
			AVG(AMOUNT) AS avg_amount
		FROM ORDERS 
		GROUP BY CUS_ID 
	) AS SUMMARY;










