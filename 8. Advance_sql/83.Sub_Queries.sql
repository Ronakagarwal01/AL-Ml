-- A Subquery or Inner Query or a Nested Query is a query within another SQL Query . It involves 2 select statment 

CREATE TABLE CUSTOMER(
CUS_ID INT PRIMARY KEY,
NAME VARCHAR(50),
CITY VARCHAR(50)
);


