-- Rollback is used to undo the uncommited changes 


CREATE DATABASE  PRIME;
USE PRIME;

CREATE TABLE ACCOUNT(
ID INT PRIMARY KEY AUTO_INCREMENT,
NAME VARCHAR(50),
BALANCE DECIMAL(10,2)
);

INSERT INTO ACCOUNT
(NAME , BALANCE)
VALUES
('ADAM',500.00),
('BOB',300.00),
('CHARLIE',1000.00);

SELECT * FROM ACCOUNT;


-- Rollback is used to undo the uncommited changes , ONLY UNCOMMITED CHANGES 
START TRANSACTION;

UPDATE ACCOUNT SET BALANCE = BALANCE - 50 WHERE ID = 1;
UPDATE ACCOUNT SET BALANCE = BALANCE + 50 WHERE ID = 2;
ROLLBACK;

SELECT * FROM ACCOUNT;




