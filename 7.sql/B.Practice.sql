-- create a table to store student info (roll no , name , city , marks )



USE COLLEGE ;

CREATE TABLE STUDENT (

ROLL_NO INT PRIMARY KEY,
NAME VARCHAR(50),
CITY VARCHAR(50),
MARKS INT

);

