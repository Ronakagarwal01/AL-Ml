-- FIND NAMES OF ALL CITYES WHERE STUDENT ARE FROM (UNIQUE CITIES )

SELECT DISTINCT CITY
FROM STUDENT ;


SELECT CITY
FROM STUDENT 
GROUP BY CITY ;



-- FIND THE MAXIMUM MARKS OF STUDENT FROM EACH CITY 

SELECT CITY , MAX(MARKS)
FROM STUDENT 
GROUP BY CITY;



-- FIND THE AVERAGE OF THE CLASS 

SELECT AVG(MARKS)
FROM STUDENT;



